'use strict';
// Build a self-contained, offline browser encoder from the already pinned QR
// dependency. No runtime dependency installation or third-party address service.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),base=path.join(root,'lib/wpay/auth/runtime/dependencies/node_modules'),modules=[],ids=new Map();
function include(file){
 if(ids.has(file))return ids.get(file);
 const id=modules.length;ids.set(file,id);modules.push('');
 const source=fs.readFileSync(file,'utf8').replace(/require\(['"]([^'"]+)['"]\)/g,(_,name)=>{
  const target=require.resolve(name,{paths:[path.dirname(file)]});
  if(!target.startsWith(base+path.sep))throw Error('Unexpected QR dependency: '+name);
  return 'load('+include(target)+')';
 });modules[id]='function(module,exports,load){\n'+source+'\n}';return id;
}
const qr=include(path.join(base,'qrcode/lib/core/qrcode.js')),renderer=include(path.join(base,'qrcode/lib/renderer/canvas.js'));
const license=fs.readFileSync(path.join(base,'qrcode/license'),'utf8');
const output='/* Generated by scripts/build-user-deposit-qr.js. qrcode 1.5.4.\n'+license+'\n*/\n(function(root){\n"use strict";\nconst modules=['+modules.join(',\n')+'],cache={};\nfunction load(id){if(cache[id])return cache[id].exports;const module=cache[id]={exports:{}};modules[id](module,module.exports,load);return module.exports;}\nroot.WPayDepositQr=Object.freeze({draw(canvas,address){if(typeof address!=="string"||!address||address.length>256)throw Error("Invalid deposit address");return load('+renderer+').render(load('+qr+').create(address,{errorCorrectionLevel:"M"}),canvas,{width:176,margin:4,color:{dark:"#000000",light:"#ffffff"}});}});\n})(globalThis);\n';
fs.writeFileSync(path.join(root,'dev/wpay-auth/web/user-deposit-qr.js'),output);
console.log('Built User-only address QR encoder:',modules.length,'modules,',Buffer.byteLength(output),'bytes');
